#!/usr/bin/env python3
"""Write the assembly of an INCLUDE_DATA object: a reference into the user's
original, never its bytes.

    python tools/data_blob.py MODULE NAME OUT.s

Some of the game's initialized data must never enter the repository, not
even as C: compressed or encrypted data, embedded images or sounds, and data
a proprietary library uses (the DNAS authentication data, for one). A C
file that owns its .data still holds such an object in its place with a line

    INCLUDE_DATA("build/blobs/MODULE", NAME);

among its definitions. configure.py gives ninja a rule for each such line:
this script writes build/blobs/MODULE/NAME.s (git-ignored, like all of
build/), whose `.incbin` takes the object's bytes from the split target of
the module (build/orig/MODULE.bin, extracted from the user's own copy of the
game) when the file is assembled; tools/mwcc_cc.py splices it into the C
object's .data where the INCLUDE_DATA line is. NAME needs a line in the module's symbol file with its size:

    D_004054E0 = 0x4054E0; // size:0xAB60

The object's alignment is MWCC's: 16 bytes for an object of 16 bytes or
more, else 8 (the script checks that the address has it). The bytes are
taken as they are: an object with pointers into the module (relocations)
can't be an INCLUDE_DATA object, and the script refuses no word, since a
blob's words that look like addresses are not pointers.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

SYM = re.compile(r"^\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+)\s*;(.*)$")
SIZE = re.compile(r"\bsize:\s*(0x[0-9A-Fa-f]+|\d+)")


def lookup(module: str, name: str) -> tuple[int, int, str, int, int]:
    """(address, size, target path, segment file offset, segment vram) of NAME."""
    import yaml
    path = ROOT / ("config/main.yaml" if module == "main" else f"config/overlays/{module}.yaml")
    cfg = yaml.safe_load(path.read_text(encoding="utf-8"))
    opts = cfg["options"]
    sym_files = opts.get("symbol_addrs_path", [])
    sym_files = [sym_files] if isinstance(sym_files, str) else sym_files
    found = None
    for sf in sym_files:
        p = ROOT / sf
        if not p.exists() or not sf.startswith("config/"):
            continue
        for line in p.read_text(encoding="utf-8").splitlines():
            m = SYM.match(line)
            if m and m.group(1) == name:
                sm = SIZE.search(m.group(3))
                if not sm:
                    sys.exit(f"data_blob.py: {name} in {sf} has no `// size:`; INCLUDE_DATA needs one")
                found = (int(m.group(2), 16), int(sm.group(1), 0))
    if found is None:
        sys.exit(f"data_blob.py: {name} is not in the symbol files of {path.relative_to(ROOT)}"
                 f" (add `{name} = 0xADDR; // size:0xN` to config/symbols/{module}.txt)")
    code = next(s for s in cfg["segments"] if isinstance(s, dict) and s.get("type") == "code")
    return found[0], found[1], opts["target_path"], code["start"], code["vram"]


def main() -> int:
    if len(sys.argv) != 4:
        sys.exit(__doc__.split("\n\n")[1])
    module, name, out = sys.argv[1:]
    addr, size, target, start, vram = lookup(module, name)
    align = 4 if size >= 16 else 3
    if addr % (1 << align):
        sys.exit(f"data_blob.py: {name} at 0x{addr:08X} is not {1 << align}-aligned:"
                 " MWCC could not have placed an object of this size there")
    off = addr - vram + start
    tpath = ROOT / target
    if tpath.exists() and off + size > tpath.stat().st_size:
        sys.exit(f"data_blob.py: {name} (0x{off:X} + 0x{size:X}) is past the end of {target}")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(
        f"/* {name}: generated by tools/data_blob.py from the user's original. Never commit. */\n"
        '.section .data, "wa"\n'
        f".align {align}\n"
        f".global {name}\n"
        f".type {name}, @object\n"
        f"{name}:\n"
        f'.incbin "{target}", 0x{off:X}, 0x{size:X}\n'
        f".size {name}, 0x{size:X}\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
